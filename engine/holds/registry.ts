/**
 * HOLD REGISTRY — orchestrator-owned and FROZEN.
 *
 * Three workers build hold families in parallel (W05a duplicate, W05b variance,
 * W05c cardinality). Without a pre-existing entry point they would each invent one, all
 * three would edit the same file, and the parallelism bought by splitting W05 would be
 * spent resolving the collision. So the entry point exists before any of them start, and
 * none of them may edit it.
 *
 * A family exports an applicator from its own directory. The orchestrator wires it in
 * below at the Wave 3 merge gate. If you are a worker reading this: add your applicator to
 * YOUR directory, export it, and report the export path. Do not edit this file — the
 * ownership gate denies it before the scope check runs (quarantine Q1).
 *
 * The policy table is here rather than in each family because a hold's policy is a
 * DOMAIN fact, not an implementation detail. Whether a hold auto-releases, and whether
 * accounting entries may be created while it is on, mirrors Oracle Payables — and the
 * worker that raises a hold should not also be the one deciding it can be released
 * without a human. That separation is the same principle as freezing the amount cap in
 * eval/thresholds.json rather than in the code that enforces it.
 */


// Orchestrator-owned. `pnpm lock:thresholds` — run once at the Wave 2 gate.
//
// Hashes eval/thresholds.json into eval/thresholds.lock. Both are frozen paths, so a
// worker can change neither. This is the mechanical answer to quarantine trigger Q2:
// "lower the floor until the build goes green" stops being available.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { sha256 } from './_hash.mjs';

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const SRC = join(ROOT, 'eval', 'thresholds.json');
const LOCK = join(ROOT, 'eval', 'thresholds.lock');

if (!existsSync(SRC)) {
  console.error('lock:thresholds: FAIL — eval/thresholds.json does not exist. W03 must land first.');
  process.exit(1);
}

const raw = readFileSync(SRC);
const digest = sha256(raw);

let parsed;
try {
  parsed = JSON.parse(raw.toString('utf8'));
} catch (err) {
  console.error(`lock:thresholds: FAIL — eval/thresholds.json is not valid JSON: ${err.message}`);
  process.exit(1);
}

const body = [
  '# HOLDFAST THRESHOLD LOCK',
  '# Generated by `pnpm lock:thresholds`. Frozen. A worker may not regenerate this.',
  '# Widening a floor to make a red build green is quarantine trigger Q2.',
  `# locked_at: ${new Date().toISOString()}`,
  `sha256: ${digest}`,
  '',
  '# Floors in force at lock time (informational — thresholds.json is authoritative):',
  ...Object.entries(parsed).flatMap(([k, v]) =>
    typeof v === 'object' && v !== null
      ? Object.entries(v).map(([k2, v2]) => `#   ${k}.${k2} = ${JSON.stringify(v2)}`)
      : [`#   ${k} = ${JSON.stringify(v)}`]
  ),
  '',
].join('\n');

writeFileSync(LOCK, body, 'utf8');
console.log(`lock:thresholds: wrote eval/thresholds.lock — sha256 ${digest.slice(0, 12)}`);

// ─────────────────────────────────────────────────────────────────────────────
// The family interface — what each of W05a/b/c exports
// ─────────────────────────────────────────────────────────────────────────────

/** Everything a family may see. Deliberately excludes the answer key. */
export interface HoldContext {
  readonly run_id: RunId;
  readonly case_id: CaseId;
  readonly invoice: Invoice;
  /** Payments in the date window, already normalised. */
  readonly payments: readonly Payment[];
  /** Ranked candidates from engine/match, read-only. */
  readonly candidates: readonly MatchCandidate[];
  /** Every other invoice in the run — duplicate detection runs over invoices. */
  readonly ledger: readonly Invoice[];
  /** Frozen policy constants from eval/thresholds.json (`policy` block only). */
  readonly policy: {
    readonly amount_cap_paise: number;
    readonly date_window_days: number;
    readonly max_subset_size: number;
  };
}

/**
 * A family proposes holds. It does not release them, and it does not decide a case.
 * `conflicts` may not be empty: every held invoice must carry at least one conflict, and
 * a hold with none is a policy bug that fails loudly rather than emitting an empty array.
 */
export interface HoldProposal {
  readonly invoice_id: InvoiceId;
  readonly type: HoldType;
  readonly reason: string;
  readonly severity: ConflictSeverity;
  readonly conflicts: readonly Conflict[];
}

export interface HoldFamily {
  /** Stable id, matching the owning worker: 'duplicate' | 'variance' | 'cardinality'. */
  readonly id: string;
  /** The hold types this family is permitted to raise. */
  readonly handles: readonly HoldType[];
  readonly apply: (ctx: HoldContext) => readonly HoldProposal[];
}

// ─────────────────────────────────────────────────────────────────────────────
// Wiring — the orchestrator fills this at the Wave 3 merge gate
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Populated by the orchestrator once W05a, W05b and W05c have merged. Kept as an explicit
 * list rather than a side-effecting `register()` call so that the set of active families
 * is readable in one place and cannot depend on module import order.
 */
const FAMILIES: readonly HoldFamily[] = [
  duplicateFamily,   // W05a — over invoices, before matching. An overpayment control.
  varianceFamily,    // W05b — deltas classified by cause; tax splits by tolerance TYPE.
  cardinalityFamily, // W05c — bounded subset-sum; an empty set rather than a guess on a tie.
  // W05d — `matching` and `no_reference`. Added after the assembled engine was first
  // measured and both types showed 0.0 recall: the original three briefs covered nine of
  // eleven hold types and these two had no owner. It speaks last and only where no other
  // family did, so it can never mask a sibling's stronger claim.
  matchingFamily,
];

export function registeredFamilies(): readonly HoldFamily[] {
  return FAMILIES;
}

/**
 * Runs every registered family and returns their proposals unchanged.
 *
 * Two invariants enforced here rather than trusted to each family:
 *  - a family may only raise hold types it declared in `handles`
 *  - a proposal must carry at least one conflict
 *
 * Both throw rather than filtering. A silently dropped hold is an invoice that gets paid,
 * and "fail loudly" is cheaper than that every time.
 */
export function applyAll(ctx: HoldContext): readonly HoldProposal[] {
  const out: HoldProposal[] = [];
  for (const family of FAMILIES) {
    for (const p of family.apply(ctx)) {
      if (!family.handles.includes(p.type)) {
        throw new Error(
          `hold registry: family "${family.id}" raised "${p.type}", which it does not declare in handles`
        );
      }
      if (p.conflicts.length === 0) {
        throw new Error(
          `hold registry: family "${family.id}" raised "${p.type}" with no conflict. ` +
            'Every held invoice must carry at least one conflict; an empty array is a policy bug.'
        );
      }
      out.push(p);
    }
  }
  return out;
}

/** Every hold type has exactly one policy slot. Checked at module load, not in a test. */
for (const t of HOLD_TYPES) {
  if (!HOLD_POLICY[t]) throw new Error(`hold registry: no policy declared for hold type "${t}"`);
}
